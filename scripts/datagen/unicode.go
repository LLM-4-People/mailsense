package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"
)

// Inputs of the unicode generator (file names in the source directory).
const (
	ucdData     = "UnicodeData.txt"
	ucdPropList = "PropList.txt"
	ucdScripts  = "Scripts.txt"
	ucdAliases  = "PropertyValueAliases.txt"
	ucdFolding  = "CaseFolding.txt"
	cldrScripts = "scriptMetadata.txt"
	cldrLatin   = "Latin-ASCII.xml"
)

const sourceNote = "generated by scripts/update-unicode-data.sh from the pinned Unicode Character Database and CLDR (unicode-pin.json); edit only the hand-kept keys, then re-run the script"

// scriptsFile is mail/scripts.json. Spaceless is generated; SubstringExtra
// is a hand-kept decision carried over.
type scriptsFile struct {
	Doc            string   `json:"_doc"`
	Source         string   `json:"_source"`
	Spaceless      []string `json:"spaceless"`
	SubstringExtra []string `json:"substring_extra"`
}

// foldFile is mail/fold.json. Letters is generated; StripMarks is a
// hand-kept decision carried over.
type foldFile struct {
	Doc        string            `json:"_doc"`
	Source     string            `json:"_source"`
	Letters    map[string]string `json:"letters"`
	StripMarks []string          `json:"strip_marks"`
}

// punctuationFile is mail/punctuation.json (wholly generated).
type punctuationFile struct {
	Doc           string   `json:"_doc"`
	Source        string   `json:"_source"`
	QuestionMarks []string `json:"question_marks"`
	// AfterScript: characters that are a question mark after a letter of
	// the scripts listed (U+003B after a Greek letter: U+037E GREEK
	// QUESTION MARK is canonically U+003B).
	AfterScript map[string][]string `json:"question_marks_after_script"`
}

func unicodeData(src, out string) error {
	chars, err := unicodeChars(filepath.Join(src, ucdData))
	if err != nil {
		return err
	}
	var sf scriptsFile
	if err := readJSON(filepath.Join(out, "scripts.json"), &sf); err != nil {
		return err
	}
	if sf.Spaceless, err = spacelessScripts(src); err != nil {
		return err
	}
	sf.Source = sourceNote
	var ff foldFile
	if err := readJSON(filepath.Join(out, "fold.json"), &ff); err != nil {
		return err
	}
	if ff.Letters, err = asciiLetters(src, chars); err != nil {
		return err
	}
	ff.Source = sourceNote
	pf := punctuationFile{Source: sourceNote, Doc: "Question marks of every script: the characters whose Unicode name contains QUESTION MARK and that have Terminal_Punctuation=Yes (PropList.txt), in code point order. question_marks_after_script: a question mark whose canonical decomposition is one other character (UnicodeData.txt: U+037E GREEK QUESTION MARK is U+003B SEMICOLON, and NFC writes it so) makes that character a question mark after a letter of the script its name begins with (PropertyValueAliases.txt script names)."}
	if pf.QuestionMarks, err = questionMarks(src, chars); err != nil {
		return err
	}
	if pf.AfterScript, err = questionMarksAfterScript(src, chars, pf.QuestionMarks); err != nil {
		return err
	}
	for name, v := range map[string]any{"scripts.json": sf, "fold.json": ff, "punctuation.json": pf} {
		if err := writeJSON(out, name, v); err != nil {
			return err
		}
	}
	return nil
}

// spacelessScripts: CLDR scriptMetadata field 7 ("LB letters": line breaks
// between letters) is YES, mapped to the UCD long script names (Go's
// unicode.Scripts keys); CLDR codes that are no UCD script (Hanb, Jpan…)
// are combinations of listed ones and are left out.
func spacelessScripts(src string) ([]string, error) {
	long := map[string]string{}
	if err := eachRecord(filepath.Join(src, ucdAliases), func(f []string) {
		if len(f) >= 3 && f[0] == "sc" {
			long[f[1]] = f[2]
		}
	}); err != nil {
		return nil, err
	}
	var out []string
	err := eachRecord(filepath.Join(src, cldrScripts), func(f []string) {
		if len(f) > 7 && f[7] == "YES" && long[f[0]] != "" && !slices.Contains(out, long[f[0]]) {
			out = append(out, long[f[0]])
		}
	})
	slices.Sort(out)
	if err == nil && len(out) == 0 {
		err = fmt.Errorf("%s: no script with LB letters", cldrScripts)
	}
	return out, err
}

// latinRule is one "X → Y ;" rule of the CLDR Latin-ASCII transform.
var latinRule = regexp.MustCompile(`^(\S) → ([a-z]+) ;`)

// asciiLetters: the Latin-ASCII rules mapping one lowercase Latin letter
// (gc=Ll, Script=Latin) to ASCII letters, kept only where nothing else
// folds it: no decomposition (NFD/NFKC handle those) and no case folding
// (ß → ss is case folding).
func asciiLetters(src string, chars map[rune]char) (map[string]string, error) {
	latin, err := property(filepath.Join(src, ucdScripts), "Latin")
	if err != nil {
		return nil, err
	}
	folded := map[rune]bool{}
	if err := eachRecord(filepath.Join(src, ucdFolding), func(f []string) {
		if len(f) >= 3 && (f[1] == "C" || f[1] == "F") {
			if r, _, ok := codeRange(f[0]); ok {
				folded[r] = true
			}
		}
	}); err != nil {
		return nil, err
	}
	raw, err := os.ReadFile(filepath.Join(src, cldrLatin))
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, line := range strings.Split(string(raw), "\n") {
		m := latinRule.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		r, _ := utf8.DecodeRuneInString(m[1])
		c := chars[r]
		if c.category == "Ll" && latin[r] && c.decomposition == "" && !folded[r] {
			out[m[1]] = m[2]
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no letter rule", cldrLatin)
	}
	return out, nil
}

// questionMarks: name contains QUESTION MARK and Terminal_Punctuation=Yes.
// questionMarksAfterScript maps the canonical singleton of a question
// mark to the script named at the start of the question mark's name.
func questionMarksAfterScript(src string, chars map[rune]char, marks []string) (map[string][]string, error) {
	var scripts []string // long script names, upper case with spaces (UCD names use them)
	if err := eachRecord(filepath.Join(src, ucdAliases), func(f []string) {
		if len(f) >= 3 && f[0] == "sc" {
			scripts = append(scripts, f[2])
		}
	}); err != nil {
		return nil, err
	}
	out := map[string][]string{}
	for _, m := range marks {
		c := chars[[]rune(m)[0]]
		d := strings.Fields(c.decomposition)
		if len(d) != 1 || strings.HasPrefix(d[0], "<") {
			continue // no canonical singleton
		}
		target, _, ok := codeRange(d[0])
		if !ok {
			return nil, fmt.Errorf("%U: decomposition %q", []rune(m)[0], c.decomposition)
		}
		for _, sc := range scripts {
			if strings.HasPrefix(c.name, strings.ToUpper(strings.ReplaceAll(sc, "_", " "))+" ") && !slices.Contains(out[string(target)], sc) {
				out[string(target)] = append(out[string(target)], sc)
			}
		}
	}
	return out, nil
}

func questionMarks(src string, chars map[rune]char) ([]string, error) {
	terminal, err := property(filepath.Join(src, ucdPropList), "Terminal_Punctuation")
	if err != nil {
		return nil, err
	}
	var codes []rune
	for r, c := range chars {
		if terminal[r] && strings.Contains(c.name, "QUESTION MARK") {
			codes = append(codes, r)
		}
	}
	slices.Sort(codes)
	out := make([]string, len(codes))
	for i, r := range codes {
		out[i] = string(r)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no question mark found")
	}
	return out, nil
}
