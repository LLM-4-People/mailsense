// Inputs of the locale generator (relative to the source directory).
const (
	cldrDir          = "cldr"
	cldrCoverage     = "cldr/coverageLevels.txt"
	cldrSupplemental = "cldr/supplementalData.xml"
	cldrLikely       = "cldr/likelySubtags.xml"
	cldrMetadata     = "cldr/supplementalMetadata.xml"
	udhrDir          = "udhr"
	confusablesFile  = "confusables.txt"
)

const localeSourceNote = "generated by scripts/update-locale-data.sh from the pinned CLDR, UDHR in XML and Unicode security data (pin.json) with the parameters of params.json; never edit by hand"

// localeParams is internal/locale/params.json (hand-kept choices).
type localeParams struct {
	Doc            string   `json:"_doc"`
	Coverage       []string `json:"cldr_coverage"`
	UDHRMinStage   int      `json:"udhr_min_stage"`
	UDHRStatus     []string `json:"udhr_status"`
	NgramMax       int      `json:"ngram_max"`
	ProfileSize    int      `json:"profile_size"`
	MinScriptShare float64  `json:"min_script_share"`
	ExcludeASCII   bool     `json:"symbol_letters_ascii_excluded"`
	AuxWeight      float64  `json:"exemplar_auxiliary_weight"`
	OutsideWeight  float64  `json:"exemplar_outside_weight"`
	DateLengths    []string `json:"date_lengths"`
	DateSkeletons  []string `json:"date_skeletons"`
	TimeLengths    []string `json:"time_lengths"`
	TimeSkeletons  []string `json:"time_skeletons"`
	RegionalStatus []string `json:"regional_status"`
}

// localeData generates langid.json, locales.json, currency.json and
// confusables.json into out (the locale package directory).
func localeData(src, out string) error {
	p, err := readParams(out)
	if err != nil {
		return err
	}
	ids, err := coverageLocales(filepath.Join(src, cldrCoverage), p.Coverage)
	if err != nil {
		return err
	}
	sup, err := readSupplemental(src)
	if err != nil {
		return err
	}
	langs, err := udhrProfiles(filepath.Join(src, udhrDir), ids, sup, p)
	if err != nil {
		return err
	}
	locales, symbols, err := cldrLocales(filepath.Join(src, cldrDir), langs, sup, p)
	if err != nil {
		return err
	}
	cals, err := calendarsOut(filepath.Join(src, cldrDir), locales, sup)
	if err != nil {
		return err
	}
	conf, err := confusables(filepath.Join(src, confusablesFile))
	if err != nil {
		return err
	}
	for name, v := range map[string]any{
		"langid.json": langidFile{Doc: langidDoc, Source: localeSourceNote, NgramMax: p.NgramMax, ProfileSize: p.ProfileSize,
			AuxWeight: p.AuxWeight, OutsideWeight: p.OutsideWeight, Languages: langs},
		"locales.json":     localesFile{Doc: localesDoc, Source: localeSourceNote, Calendars: cals, Locales: locales},
		"currency.json":    currencyFile{Doc: currencyDoc, Source: localeSourceNote, Codes: sup.currencies, Symbols: currencySymbols(symbols, sup.currencies, p.ExcludeASCII)},
		"confusables.json": confusablesOut{Doc: confusablesDoc, Source: localeSourceNote, Map: conf},
	} {
		if err := writeJSON(out, name, v); err != nil {
			return err
		}
	}
	return nil
}

// readParams reads params.json (the generator's choices).
func readParams(out string) (localeParams, error) {
	var p localeParams
	if err := readJSON(filepath.Join(out, "params.json"), &p); err != nil || p.ProfileSize <= 0 || p.NgramMax <= 0 || len(p.RegionalStatus) == 0 {
		return p, fmt.Errorf("params.json: %v (profile_size %d, ngram_max %d, regional_status %v)", err, p.ProfileSize, p.NgramMax, p.RegionalStatus)
	}
	return p, nil
}

// localeIDs prints the CLDR main files the locale generator reads: the
// locales of the chosen coverage levels, their regional locales
// (regionalIDs) and every locale of their inheritance chains, root last
// included; sorted. A regional locale CLDR ships no file for (default
// content) inherits its language's data entirely.
func localeIDs(src, out string) error {
	p, err := readParams(out)
	if err != nil {
		return err
	}
	ids, err := coverageLocales(filepath.Join(src, cldrCoverage), p.Coverage)
	if err != nil {
		return err
	}
	sup, err := readSupplemental(src)
	if err != nil {
		return err
	}
	set := map[string]bool{}
	for _, id := range ids {
		for _, v := range append([]string{id}, regionalIDs(id, sup, p.RegionalStatus)...) {
			for _, c := range chain(v, sup.parents) {
				set[c] = true
			}
		}
	}
	for _, id := range slices.Sorted(maps.Keys(set)) {
		fmt.Println(id)
	}
	return nil
}

// regionalIDs are the regional locales of a locale id: <id>_<territory>
// for every territory where CLDR gives its language (territoryInfo) one
// of the statuses of params.json regional_status, sorted. Their date
// patterns are the language's too (en_GB writes d/M/y, en_US M/d/y).
func regionalIDs(id string, sup *supplemental, statuses []string) []string {
	var out []string
	for _, r := range sup.official[id] {
		if slices.Contains(statuses, r.status) {
			out = append(out, id+"_"+r.territory)
		}
	}
	slices.Sort(out)
	return out
}

// coverageLocales lists the CLDR locale ids at the chosen coverage levels.
func coverageLocales(path string, levels []string) ([]string, error) {
	var out []string
	err := eachRecord(path, func(f []string) {
		if len(f) >= 2 && slices.Contains(levels, f[1]) {
			out = append(out, f[0])
		}
	})
	slices.Sort(out)
	if err == nil && len(out) == 0 {
		err = fmt.Errorf("%s: no locale at levels %v", path, levels)
	}
	return out, err
}

// cldrLocales resolves the calendar and number data of every language of
// the profiles — the language's locale joined with its regional locales
// (regionalIDs) —, its calendars (those of its likely territory), and
// collects the currency symbols of their chains.
func cldrLocales(dir string, langs []langProfile, sup *supplemental, p localeParams) (map[string]cldrLocale, map[string][]string, error) {
	cache := map[string]*ldml{}
	load := func(id string) (*ldml, error) {
		if l, ok := cache[id]; ok {
			return l, nil
		}
		l, err := readLDML(dir, id)
		if os.IsNotExist(err) {
			l, err = &ldml{}, nil // no file of its own (default content, a truncated parent): it inherits everything
		}
		cache[id] = l
		return l, err
	}
	files := func(id string) ([]*ldml, error) {
		var out []*ldml
		for _, c := range chain(id, sup.parents) {
			l, err := load(c)
			if err != nil {
				return nil, err
			}
			out = append(out, l)
		}
		return out, nil
	}
	out, symbols := map[string]cldrLocale{}, map[string][]string{}
	for li := range langs {
		lang := &langs[li]
		own, err := files(lang.Locale)
		if err != nil {
			return nil, nil, err
		}
		loc := buildLocale(own, p)
		lang.Letters, lang.Auxiliary = exemplars(own)
		all := own
		for _, id := range regionalIDs(lang.Locale, sup, p.RegionalStatus) {
			fs, err := files(id)
			if err != nil {
				return nil, nil, err
			}
			loc.join(buildLocale(fs, p))
			all = append(all, fs...)
		}
		loc.Calendars = sup.calendarsOf(lang.Locale)
		out[lang.Tag] = loc
		for _, l := range all {
			for _, c := range l.Currencies {
				for _, s := range c.Symbols {
					if v := strings.TrimSpace(s.Value); v != "" && v != inherit && !slices.Contains(symbols[v], c.Type) {
						symbols[v] = append(symbols[v], c.Type)
					}
				}
			}
		}
	}
	root, err := load("root")
	if err != nil {
		return nil, nil, err
	}
	out[undetermined] = numericOnly(buildLocale([]*ldml{root}, p))
	return out, symbols, nil
}

// calendarsOf are the calendars of a locale's likely territory
// (likelySubtags, calendarPreferenceData), preferred first.
func (s *supplemental) calendarsOf(id string) []string {
	tag := s.likely[id]
	if tag == "" {
		tag = s.likely[strings.SplitN(id, "_", 2)[0]]
	}
	parts := strings.Split(tag, "_")
	if prefs, ok := s.calendarPrefs[parts[len(parts)-1]]; ok && len(parts) > 1 {
		return slices.Clone(prefs)
	}
	return slices.Clone(s.calendarPrefs["001"])
}

// calendarsOut describes every calendar of the shipped locales: its
// system and current era (calendarData) and whether its months are the
// Gregorian ones (root.xml aliases buddhist, japanese, roc months to them).
func calendarsOut(dir string, locales map[string]cldrLocale, sup *supplemental) (map[string]calendarData, error) {
	root, err := readLDML(dir, "root")
	if err != nil {
		return nil, err
	}
	out := map[string]calendarData{}
	for _, l := range locales {
		for _, c := range l.Calendars {
			info, ok := sup.calendars[c]
			if !ok {
				return nil, fmt.Errorf("calendar %q has no calendarData", c)
			}
			d := calendarData{calendarInfo: info, GregorianMonths: c == "gregorian"}
			for _, rc := range root.Calendars {
				if rc.Type == c && strings.Contains(rc.MonthsAlias.Path, "@type='gregorian'") {
					d.GregorianMonths = true
				}
			}
			out[c] = d
		}
	}
	return out, nil
}

// undetermined is the locale of text whose language is not known: root's
// numeric patterns with a year (ISO 8601), no names (root's are placeholders).
const undetermined = "und"

func numericOnly(l cldrLocale) cldrLocale {
	keep := func(ps []string, needYear bool) []string {
		var out []string
		for _, p := range ps {
			u := unquoted(p)
			if !strings.ContainsAny(u, "LEcabB") && !strings.Contains(u, "MMM") && (!needYear || strings.Contains(u, "y")) {
				out = append(out, p)
			}
		}
		return out
	}
	// dates with a year only: ISO 8601 calendar dates (y-MM-dd). Root's
	// year-less MM-dd is no ISO 8601 form, and read in every language it
	// takes ranges ("10-12") for dates.
	return cldrLocale{DatePatterns: keep(l.DatePatterns, true), TimePatterns: keep(l.TimePatterns, false), Decimals: l.Decimals, Groups: l.Groups,
		Calendars: []string{"gregorian"}}
}

// unquoted drops the quoted literals of a CLDR pattern.
func unquoted(p string) string {
	var b strings.Builder
	in := false
	for _, r := range p {
		if r == '\'' {
			in = !in
			continue
		}
		if !in {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// Output files.
type (
	langidFile struct {
		Doc           string        `json:"_doc"`
		Source        string        `json:"_source"`
		NgramMax      int           `json:"ngram_max"`
		ProfileSize   int           `json:"profile_size"`
		AuxWeight     float64       `json:"exemplar_auxiliary_weight"`
		OutsideWeight float64       `json:"exemplar_outside_weight"`
		Languages     []langProfile `json:"languages"`
	}
	localesFile struct {
		Doc       string                  `json:"_doc"`
		Source    string                  `json:"_source"`
		Calendars map[string]calendarData `json:"calendars"`
		Locales   map[string]cldrLocale   `json:"locales"`
	}
	// calendarData is one calendar a shipped locale may write dates in.
	calendarData struct {
		calendarInfo
		GregorianMonths bool `json:"gregorian_months"` // its months are the Gregorian ones (root aliases them)
	}
	currencyFile struct {
		Doc     string              `json:"_doc"`
		Source  string              `json:"_source"`
		Codes   []string            `json:"codes"`
		Symbols map[string][]string `json:"symbols"`
	}
	confusablesOut struct {
		Doc    string            `json:"_doc"`
		Source string            `json:"_source"`
		Map    map[string]string `json:"map"`
	}
)

