package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// prefixesFile is mail/subject_prefixes.json. Wikipedia is generated from
// the pinned revision; Extras are hand-kept (each with its provenance)
// and carried over.
type prefixesFile struct {
	Doc       string        `json:"_doc"`
	Source    string        `json:"_source"`
	Wikipedia []string      `json:"wikipedia"`
	Extras    []prefixExtra `json:"extras"`
}

type prefixExtra struct {
	Prefix string `json:"prefix"`
	Note   string `json:"note"`
}

// Wikitext of "List of email subject abbreviations": the standard
// prefixes are the bold words of the bullets of "Standard prefixes"; the
// localized ones the RE and FW cells of the "Abbreviations in other
// languages" table (bold words, or the cell text without bold).
var (
	boldRE    = regexp.MustCompile(`'''([^']+)'''`)
	sectionRE = regexp.MustCompile(`(?m)^==\s*([^=]+?)\s*==\s*$`)
	glossRE   = regexp.MustCompile(`\(''[^)]*''\)`)
)

func prefixData(wikitext, out string) error {
	raw, err := os.ReadFile(wikitext)
	if err != nil {
		return err
	}
	sections := splitSections(string(raw))
	std, table := sections["Standard prefixes"], sections["Abbreviations in other languages"]
	if std == "" || table == "" {
		return fmt.Errorf("%s: the standard-prefix section or the language table is missing", wikitext)
	}
	var words []string
	for _, line := range strings.Split(std, "\n") {
		if strings.HasPrefix(line, "* ") {
			for _, m := range boldRE.FindAllStringSubmatch(line, -1) {
				words = addWord(words, m[1])
			}
		}
	}
	for _, cell := range tableCells(table) {
		words = append(words, cellWords(cell)...)
	}
	var pf prefixesFile
	if err := readJSON(filepath.Join(out, "subject_prefixes.json"), &pf); err != nil {
		return err
	}
	pf.Wikipedia = dedupe(words)
	if len(pf.Wikipedia) == 0 {
		return fmt.Errorf("%s: no prefix found", wikitext)
	}
	pf.Source = "generated by scripts/update-prefixes.sh from the pinned revision of Wikipedia's \"List of email subject abbreviations\" (prefixes-pin.json); extras are hand-kept"
	return writeJSON(out, "subject_prefixes.json", pf)
}

func splitSections(text string) map[string]string {
	out := map[string]string{}
	idx := sectionRE.FindAllStringSubmatchIndex(text, -1)
	for i, m := range idx {
		end := len(text)
		if i+1 < len(idx) {
			end = idx[i+1][0]
		}
		out[text[m[2]:m[3]]] = text[m[1]:end]
	}
	return out
}

// tableCells returns the RE and FW cells (2nd and 3rd) of every row.
func tableCells(table string) []string {
	var out []string
	for _, row := range strings.Split(table, "\n|-")[1:] {
		var cells []string
		for _, line := range strings.Split(row, "\n") {
			if strings.HasPrefix(line, "|") && !strings.HasPrefix(line, "|}") && !strings.HasPrefix(line, "|-") {
				cells = append(cells, strings.TrimSpace(line[1:]))
			}
		}
		if len(cells) >= 3 {
			out = append(out, cells[1], cells[2])
		}
	}
	return out
}

func cellWords(cell string) []string {
	cell = strings.TrimSpace(glossRE.ReplaceAllString(cell, ""))
	var out []string
	for _, m := range boldRE.FindAllStringSubmatch(cell, -1) {
		out = addWord(out, m[1])
	}
	if len(out) == 0 && cell != "" {
		out = addWord(out, cell)
	}
	return out
}

// addWord adds a prefix as written, without its colon.
func addWord(words []string, w string) []string {
	w = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(w), ":"))
	if w == "" {
		return words
	}
	return append(words, w)
}

// dedupe keeps the first spelling of each case-insensitive word.
func dedupe(words []string) []string {
	var out []string
	for _, w := range words {
		dup := false
		for _, o := range out {
			dup = dup || strings.EqualFold(o, w)
		}
		if !dup {
			out = append(out, w)
		}
	}
	return out
}
