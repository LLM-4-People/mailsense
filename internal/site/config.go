package site

import (
	"encoding/json"
	"fmt"
	"strings"
)

// yamlQuote writes a JSON string literal, which is also a valid YAML
// double-quoted scalar.
func yamlQuote(value string) string {
	body, _ := json.Marshal(value)
	return string(body)
}

// docsRel turns one page table path under docs/ into a Jekyll source path.
func docsRel(name string) string {
	return strings.TrimPrefix(name, "docs/")
}

// Config renders docs/_config.yml. The header page list and the exclude list
// come from the page table and the files present, so neither is hand-copied.
func (s Site) Config() []byte {
	var out strings.Builder
	out.WriteString("# Generated by cmd/gensite from docs/site.json. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "title: %s\n", yamlQuote(s.Product))
	fmt.Fprintf(&out, "description: %s\n", yamlQuote(s.Hero.Promise.EN))
	out.WriteString("theme: \"minima\"\n")
	fmt.Fprintf(&out, "baseurl: %s\n", yamlQuote(s.BaseURL))
	out.WriteString("url: \"\"\n")
	out.WriteString("lang: \"en\"\n")
	out.WriteString("header_pages:\n")
	for _, item := range s.Nav {
		if !item.Primary {
			continue
		}
		for _, page := range s.Pages() {
			if page.Key == item.Key {
				fmt.Fprintf(&out, "  - %s\n", yamlQuote(docsRel(page.EN)))
			}
		}
	}
	for _, page := range s.Pages() {
		if page.Key == "index" {
			fmt.Fprintf(&out, "  - %s\n", yamlQuote(docsRel(page.FR)))
		}
	}
	out.WriteString("markdown: \"kramdown\"\n")
	out.WriteString("plugins:\n  - \"jekyll-relative-links\"\n")
	out.WriteString("relative_links:\n  enabled: true\n  collections: false\n")
	out.WriteString("sass:\n  style: \"compressed\"\n")
	out.WriteString("exclude:\n")
	for _, name := range s.excluded {
		fmt.Fprintf(&out, "  - %s\n", yamlQuote(name))
	}
	out.WriteString("defaults:\n")
	out.WriteString("  - scope:\n      path: \"\"\n    values:\n      lang: \"en\"\n")
	out.WriteString("  - scope:\n      path: \"fr\"\n    values:\n      lang: \"fr\"\n")
	return []byte(out.String())
}
