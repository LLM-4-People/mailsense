package ui

import (
	"bytes"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// bundleHeader is the generated prologue of the served /app.js. The source
// modules are concatenated inside one strict IIFE, exactly as the pre-split
// app.js was, so every declaration keeps its shared scope and call sites do
// not change.
const bundleHeader = `/* Code generated by internal/ui/bundle.go from js/manifest.txt. DO NOT EDIT. */
"use strict";

/*
 * Mailsense's embedded desktop shell.
 *
 * The launch token arrives in the URL fragment, is copied to sessionStorage
 * and is removed from the address with history.replaceState before the first
 * API call. It is never written to the DOM, the console or an error message.
 */
(() => {
`

const bundleFooter = "})();\n"

// Bundle builds the served application script from the modules listed in
// js/manifest.txt. It is the one generator of /app.js: the manifest is the
// declaration order, every embedded module must be listed exactly once, and
// the result is deterministic so the gate can compare it byte for byte.
func Bundle() ([]byte, error) {
	names, err := moduleNames("js", ".js")
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(bundleHeader)
	for _, name := range names {
		body, err := fs.ReadFile(Files, path.Join("js", name))
		if err != nil {
			return nil, fmt.Errorf("ui: read module %s: %w", name, err)
		}
		b.Write(body)
		if len(body) > 0 && body[len(body)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	b.WriteString(bundleFooter)
	return b.Bytes(), nil
}

// CSSBundle builds the served stylesheet from the modules listed in
// css/manifest.txt. Like Bundle it is deterministic and its output is
// committed as the generated app.css, so the gate can detect a stale or
// hand-edited stylesheet.
func CSSBundle() ([]byte, error) {
	names, err := moduleNames("css", ".css")
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(cssBundleHeader)
	for _, name := range names {
		body, err := fs.ReadFile(Files, path.Join("css", name))
		if err != nil {
			return nil, fmt.Errorf("ui: read stylesheet %s: %w", name, err)
		}
		b.Write(body)
		if len(body) > 0 && body[len(body)-1] != '\n' {
			b.WriteByte('\n')
		}
	}
	return b.Bytes(), nil
}

const cssBundleHeader = "/* Code generated by internal/ui/bundle.go from css/manifest.txt. DO NOT EDIT. */\n"

// moduleNames reads and validates one manifest: entries are plain file names
// in declaration order, comments and blank lines are ignored, and the glob of
// the directory must contain exactly the listed set. A new module that is not
// in the manifest therefore fails at start-up, not silently in production.
func moduleNames(dir, ext string) ([]string, error) {
	raw, err := fs.ReadFile(Files, path.Join(dir, "manifest.txt"))
	if err != nil {
		return nil, fmt.Errorf("ui: read %s/manifest.txt: %w", dir, err)
	}
	seen := map[string]bool{}
	var names []string
	for _, line := range strings.Split(string(raw), "\n") {
		name := strings.TrimSpace(line)
		if name == "" || strings.HasPrefix(name, "#") {
			continue
		}
		if path.Base(name) != name || !strings.HasSuffix(name, ext) {
			return nil, fmt.Errorf("ui: %s/manifest.txt entry %q is not a plain %s file name", dir, name, ext)
		}
		if seen[name] {
			return nil, fmt.Errorf("ui: %s/manifest.txt lists %s twice", dir, name)
		}
		seen[name] = true
		names = append(names, name)
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("ui: %s/manifest.txt lists no modules", dir)
	}
	all, err := fs.Glob(Files, path.Join(dir, "*"+ext))
	if err != nil {
		return nil, err
	}
	var unlisted []string
	for _, full := range all {
		name := path.Base(full)
		if !seen[name] {
			unlisted = append(unlisted, name)
		}
	}
	if len(unlisted) > 0 {
		sort.Strings(unlisted)
		return nil, fmt.Errorf("ui: %s/*%s not listed in manifest.txt: %s", dir, ext, strings.Join(unlisted, ", "))
	}
	if len(all) != len(names) {
		return nil, fmt.Errorf("ui: %s/manifest.txt lists %d modules but %d exist", dir, len(names), len(all))
	}
	return names, nil
}
